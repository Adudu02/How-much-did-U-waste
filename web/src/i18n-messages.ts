export type MessageValues = Record<string, string | number>;

export function resolveLocale(value: string | null): Locale {
  return value === "en-US" ? "en-US" : "es-MX";
}

export function readLocalePreference(read: () => string | null): Locale {
  try {
    return resolveLocale(read());
  } catch {
    return "es-MX";
  }
}

export function persistLocalePreference(write: (key: string, value: string) => void, locale: Locale): void {
  try {
    write("dft.language", locale);
  } catch {
    // The active page can still use the newly selected locale.
  }
}

export function translate(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  const template = locale === "en-US" ? en[key] : es[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = values[name];
    return value === undefined ? `{${name}}` : typeof value === "number" ? new Intl.NumberFormat(locale).format(value) : String(value);
  });
}

const apiErrorKeys: Record<string, MessageKey> = {
  "not found": "api.notFound",
  "sesión no encontrada": "api.sessionNotFound",
  "skill no encontrado en el catálogo": "api.skillNotFound",
  "el skill no tiene rutas de instalación": "api.noInstallPaths",
  "format debe ser csv o json": "api.invalidExport",
  "refresh debounced (30s)": "api.refreshDebounced",
};

export function localizeApiError(locale: Locale, message: string): string {
  const key = apiErrorKeys[message];
  return key ? translate(locale, key) : message;
}
